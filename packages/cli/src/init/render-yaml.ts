import { PGMOAT_VERSION } from '@pgmoat/core';

export const AUTO_HIDE_REGEX = /(password|passwd|secret|token|api_?key|hash|salt|ssn|card)/i;

export interface RenderColumnInput {
  name: string;
  comment?: string | null;
  hidden?: boolean;
}

export interface RenderRelationInput {
  name: string;
  schema: string;
  comment?: string | null;
  columns: RenderColumnInput[];
  isStale?: boolean;
  staleDate?: string;
}

export interface RenderYamlOptions {
  serverName: string;
  description: string;
  connectionUrl: string;
  schemas: string[];
  transport?: 'stdio' | 'http';
  auditDestination?: 'file' | 'stderr' | 'postgres';
  auditPath?: string;
  relations: RenderRelationInput[];
  dateStr?: string;
}

export function renderYaml(options: RenderYamlOptions): string {
  const dateStr = options.dateStr ?? new Date().toISOString().split('T')[0];
  const transport = options.transport ?? 'stdio';
  const auditDest = options.auditDestination ?? 'file';
  const auditPath = options.auditPath ?? './pgmoat-audit';

  const lines: string[] = [];

  // Header comments
  lines.push(`# pgmoat.yaml  generated by pgmoat init ${PGMOAT_VERSION} on ${dateStr}`);
  lines.push('# Docs: https://kitalonlabs.com/pgmoat#config   Check: pgmoat validate');
  lines.push('');
  lines.push('version: 1');
  lines.push('');
  lines.push('server:');
  lines.push(`  name: ${options.serverName}`);
  lines.push(`  description: "${options.description}"`);
  lines.push('');
  lines.push(`transport: ${transport}`);
  lines.push('');
  lines.push('connection:');
  lines.push(`  url: ${options.connectionUrl}`);
  lines.push(`  schemas: [${options.schemas.join(', ')}]`);
  lines.push('');
  lines.push('mode: read-only');
  lines.push('');
  lines.push('budgets:');
  lines.push('  max_rows: 200');
  lines.push('  max_query_ms: 5000');
  lines.push('  max_payload_bytes: 65536');
  lines.push('');
  lines.push('rls:');
  lines.push('  required: false');
  lines.push('  session_variables: {}');
  lines.push('  # Example for a single-tenant process:');
  lines.push('  # session_variables:');
  lines.push('  #   app.tenant_id: env.PGMOAT_TENANT_ID');
  lines.push('');
  lines.push('policy:');
  lines.push('  allow_catalog_queries: false');
  lines.push('');
  lines.push('# ---------------------------------------------------------------------------');
  lines.push('# Tables. Your agent reads these descriptions. Keep them short and specific.');
  lines.push('# hidden: true      the agent cannot see or query it');
  lines.push('# sensitive: high   visible, masked in sample_table, redacted in audit');
  lines.push('# untrusted: true   free text written by end users; flagged in results');
  lines.push('# ---------------------------------------------------------------------------');
  lines.push('tables:');

  for (const rel of options.relations) {
    lines.push('');
    const relKey = options.schemas.length > 1 && rel.schema !== 'public'
      ? `${rel.schema}.${rel.name}`
      : rel.name;

    if (rel.isStale) {
      lines.push(`  # STALE: not found in database on ${rel.staleDate ?? dateStr}`);
    }

    const descStr = rel.comment ? JSON.stringify(rel.comment) : '""';
    const descComment = rel.comment ? '' : '   # TODO: describe';
    lines.push(`  ${relKey}:`);
    lines.push(`    description: ${descStr}${descComment}`);

    if (rel.columns && rel.columns.length > 0) {
      lines.push('    columns:');
      const maxColLen = Math.max(...rel.columns.map((c) => c.name.length));
      for (const col of rel.columns) {
        const paddedCol = `${col.name}:`.padEnd(maxColLen + 2, ' ');
        if (col.hidden) {
          lines.push(`      ${paddedCol}{ hidden: true }`);
        } else {
          const colDesc = col.comment ? JSON.stringify(col.comment) : '""';
          lines.push(`      ${paddedCol}{ description: ${colDesc} }`);
        }
      }
    }
  }

  lines.push('');
  lines.push('audit:');
  lines.push(`  destination: ${auditDest}`);
  if (auditDest === 'file') {
    lines.push(`  path: ${auditPath}`);
  }

  return lines.join('\n') + '\n';
}

