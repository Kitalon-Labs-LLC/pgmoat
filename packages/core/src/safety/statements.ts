export const FORBIDDEN_EXACT_STATEMENTS = new Set([
  'InsertStmt',
  'UpdateStmt',
  'DeleteStmt',
  'MergeStmt',
  'CopyStmt',
  'TransactionStmt',
  'VariableSetStmt',
  'LockStmt',
  'NotifyStmt',
  'ListenStmt',
  'UnlistenStmt',
] as const);

export function isForbiddenNodeType(type: string): boolean {
  if (FORBIDDEN_EXACT_STATEMENTS.has(type as unknown as 'InsertStmt')) {
    return true;
  }
  return FORBIDDEN_PREFIXES.some((prefix) => type.startsWith(prefix));
}

