import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const specPath = path.join(rootDir, 'spec', '05-pgmoat-backend-schema.md');
const outputPath = path.join(
  rootDir,
  'packages',
  'core',
  'src',
  'errors.generated.ts',
);

export function generateErrorsCode() {
  const content = fs.readFileSync(specPath, 'utf8');
  const section4 = content
    .split('## 4) Error code registry')[1]
    .split('## 5)')[0];
  const subSections = section4.split('### ');
  const entries = [];

  for (const sub of subSections) {
    if (!sub.trim()) continue;
    const lines = sub.split('\n');
    const sectionTitle = lines[0].trim();
    const sectionId = sectionTitle.split(':')[0].trim();
    const tableLines = lines.filter((l) => l.trim().startsWith('|'));
    if (tableLines.length < 3) continue;
    const headers = tableLines[0]
      .split('|')
      .map((s) => s.trim())
      .filter(Boolean);

    for (let i = 2; i < tableLines.length; i++) {
      const cells = tableLines[i]
        .split('|')
        .map((s) => s.trim())
        .slice(1, -1);
      if (!cells[0] || !cells[0].startsWith('PGM-')) continue;
      const row = {};
      headers.forEach((h, idx) => {
        row[h] = cells[idx] || '';
      });

      const code = row.Code;
      const title = (row.Cause || row.Finding || '').slice(0, 80).trim();
      let kind = row.Kind;
      if (!kind) {
        if (sectionId === '1xx') kind = 'startup';
        else if (sectionId === '21x') kind = 'refused';
        else if (sectionId === '5xx') kind = 'error';
        else if (sectionId === '6xx') kind = 'auth';
        else if (sectionId === '7xx') kind = 'doctor';
        else kind = 'error';
      }

      const httpStatus = row.HTTP ? Number(row.HTTP) : undefined;
      const fix = (
        row.Fix ||
        row['Fix shown to the agent'] ||
        row['Suggested fix'] ||
        ''
      ).trim();

      entries.push({
        code,
        title,
        section: sectionId,
        kind,
        httpStatus,
        fix,
      });
    }
  }

  const codeUnion = entries.map((e) => `  | '${e.code}'`).join('\n');
  const recordEntries = entries
    .map((e) => {
      const parts = [
        `    code: '${e.code}',`,
        `    title: ${JSON.stringify(e.title)},`,
        `    section: '${e.section}',`,
        `    kind: '${e.kind}',`,
      ];
      if (e.httpStatus) {
        parts.push(`    httpStatus: ${e.httpStatus},`);
      }
      if (e.fix) {
        parts.push(`    fix: ${JSON.stringify(e.fix)},`);
      }
      return `  '${e.code}': {\n${parts.join('\n')}\n  },`;
    })
    .join('\n');

  return `// Generated by tools/gen-errors.mjs from spec/05-pgmoat-backend-schema.md - DO NOT EDIT MANUALLY

export type ErrorCode =
${codeUnion};

export interface ErrorDefinition {
  readonly code: ErrorCode;
  readonly title: string;
  readonly section: string;
  readonly kind: string;
  readonly httpStatus?: number;
  readonly fix?: string;
}

export const ERROR_CODES: Readonly<Record<ErrorCode, ErrorDefinition>> = Object.freeze({
${recordEntries}
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const isCheck = process.argv.includes('--check');
  const code = generateErrorsCode();

  if (isCheck) {
    if (!fs.existsSync(outputPath)) {
      console.error(`Missing generated file: ${outputPath}`);
      process.exit(1);
    }
    const current = fs.readFileSync(outputPath, 'utf8');
    if (current !== code) {
      console.error(
        'Error registry is out of date. Run "pnpm gen:errors" to update it.',
      );
      process.exit(1);
    }
    console.log('Error registry is up to date.');
  } else {
    fs.writeFileSync(outputPath, code, 'utf8');
    console.log(`Generated ${outputPath}`);
  }
}
